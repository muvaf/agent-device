import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const root=process.env.AGENT_DEVICE_TEST_ROOT ?? '/Users/muvaf/github.com/callstack/agent-device-native-upstream';
const output='/private/tmp/agent-device-remaining-evidence/native';
await fs.mkdir(output,{recursive:true});
const require=createRequire(root+'/package.json');
const config=require('yaml').parse(await fs.readFile('/Users/muvaf/.lim/config.yaml','utf8'));
const instance=JSON.parse(await fs.readFile('/private/tmp/agent-device-remaining-evidence/ios-private.json','utf8'));
const {status}=instance;
Object.assign(process.env,{LIMRUN_API_KEY:config['api-key'],LIM_IOS_INSTANCE_URL:status.apiUrl,LIM_IOS_INSTANCE_TOKEN:status.token,AGENT_DEVICE_LIMRUN_IOS_RUNNER_APP:'/private/tmp/agent-device-remaining-evidence/runner/agent-device-ios-runner-0.0.0-dev.app'});
if(config['api-endpoint']) process.env.LIMRUN_BASE_URL=config['api-endpoint'];
const {createAgentDeviceClient}=await import(root+'/dist/src/index.js');
const {createInstanceClient}=await import(root+'/node_modules/@limrun/api/ios-client.mjs');
const remote=await createInstanceClient({apiUrl:status.apiUrl,token:status.token,logLevel:'error'});
const scope={tenant:'limrun',runId:'remaining-native',leaseBackend:'ios-instance',leaseProvider:'limrun',platform:'ios'};
const stateDir='/private/tmp/agent-device-remaining-evidence/native-state';
const manager=createAgentDeviceClient({stateDir,session:'ios-lease'});
const lease=await manager.leases.allocate({...scope,retainOnClose:true});
const client=createAgentDeviceClient({stateDir,session:'ios-app',...scope,leaseId:lease.leaseId,sessionIsolation:'tenant'});
const app='com.limrun.e2e-fixture';
const device={id:'limrun:ios:live',platform:'apple',appleOs:'ios',kind:'simulator',name:'Live',booted:true};
const session={device,client:remote,apiUrl:status.apiUrl,token:status.token};
const {createLimrunAppleToolProvider}=await import(root+'/src/core/interactors/limrun-ios-tools.ts');
const {withAppleToolProvider}=await import(root+'/packages/platform-apple/src/core/tool-provider.ts');
const {resolveIosSimulatorDeepLinkBundleId,resolveIosSimulatorExpoDevClientScheme}=await import(root+'/packages/platform-apple/src/core/app-resolution.ts');
const simctl=args=>remote.simctl(args).wait();
try {
 console.log('instance',instance.metadata.id);
 console.log('source',require('node:child_process').execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim());
 await client.apps.install({app,appPath:'/Users/muvaf/github.com/limrun/limrun/test/e2e/testdata/fixtures/ios/E2EFixture.app'});
 const stopped=await simctl(['terminate','booted',app]);assert.notEqual(stopped.code,0,'install unexpectedly launched the app');console.log('install-only leaves app stopped');
 const owner=await withAppleToolProvider(createLimrunAppleToolProvider(session,new AbortController().signal),()=>resolveIosSimulatorDeepLinkBundleId(device,'limrun-e2e://test',{timeoutMs:15000}));assert.equal(owner,app);console.log('downloaded plist resolves unique deep-link owner');
 await client.apps.open({app});console.log('PASS public SDK open and boot readiness');
 const logStarted=await client.observability.logs({action:'start'});
 const logPath=logStarted.path ?? logStarted.data?.path; assert.ok(logPath);
 let logText=''; const logDeadline=Date.now()+15000;
 while(Date.now()<logDeadline){logText=await fs.readFile(logPath,'utf8').catch(()=> '');if(logText.includes('e2e-fixture heartbeat'))break;await new Promise(r=>setTimeout(r,300));}
 assert.match(logText,/e2e-fixture heartbeat/);console.log('PASS daemon app log heartbeat');
 await client.observability.logs({action:'stop'});
 const snapshot=await client.capture.snapshot({interactiveOnly:true});assert.ok(snapshot.nodes.length>0);console.log('PASS shared runner snapshot',snapshot.nodes.length);
 await fs.writeFile(output+'/snapshot.json',JSON.stringify(snapshot,null,2));
 console.log('appstate',JSON.stringify(await client.command.appState()));
 await client.interactions.click({selector:'id=e2e-grid-r1c1'});
 const clicked=await client.capture.snapshot({interactiveOnly:false});
 assert.ok(clicked.nodes.some(n=>n.identifier==='e2e-tap-result' && (n.label==='r1c1'||n.value==='r1c1')),'tap did not update fixture');
 console.log('PASS selector tap updates app state');
 await client.interactions.fill({selector:'id=e2e-text-field',text:'native runner parity',delayMs:20});
 const typed=await client.capture.snapshot({interactiveOnly:false});
 assert.ok(typed.nodes.some(n=>n.identifier==='e2e-text-field'&&n.value==='native runner parity'),'text did not update');
 console.log('PASS shared fill with delay');
 const otherRecording=await remote.startRecordingSession({quality:5});
 const video=output+'/recording.mp4';
 await client.recording.record({action:'start',path:video,quality:'medium'});
 await client.capture.snapshot({interactiveOnly:false});
 await client.recording.record({action:'stop'});
 assert.equal((await fs.readFile(video)).toString('ascii',4,8),'ftyp');
 await remote.stopRecordingSession(otherRecording,{localPath:output+'/external-recording.mp4'});
 console.log('PASS MP4 recording download and independent concurrent recorder');
 await client.apps.push({app,payload:{aps:{alert:'agent-device parity test'}}});console.log('push delivered through common deployment');
 const staging=await remote.listFiles();assert.equal(staging.some(f=>f.name?.endsWith('.apns')&&f.name.startsWith('agent-device-')),false);console.log('push staging removed');
 await fs.writeFile(output+'/marker','old-data');await remote.pushFile(output+'/marker','Documents/gap-marker',{bundleId:app,containerType:'data'});
 const metadata=await remote.pullFile('.com.apple.mobile_container_manager.metadata.plist',{bundleId:app,containerType:'data'});
 await client.settings.update({setting:'clear-app-state',state:'clear',app});
 const after=await remote.pullFile('.com.apple.mobile_container_manager.metadata.plist',{bundleId:app,containerType:'data'});assert.deepEqual(after,metadata);
 const docs=await remote.listFiles('Documents',{bundleId:app,containerType:'data'});assert.equal(docs.length,0);
 const terminated=await simctl(['terminate','booted',app]);assert.notEqual(terminated.code,0,'clear unexpectedly launched app');console.log('clear state removes data, preserves identity and leaves app stopped');
 await client.apps.open({app});const shot=output+'/screenshot.png';await client.capture.screenshot({path:shot});assert.equal((await fs.readFile(shot)).toString('ascii',1,4),'PNG');console.log('runner screenshot and relaunch passed');
 await client.apps.close();console.log('PASS native integration live');
} catch(e){console.error('FAIL',e.code,e.message,JSON.stringify(e.details));process.exitCode=1;} finally {await client.apps.close().catch(()=>{});await manager.leases.release({...scope,leaseId:lease.leaseId}).catch(e=>console.error('release failed',e.message));remote.disconnect();console.log('closed session and released lease');}
